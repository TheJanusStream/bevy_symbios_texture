#[cfg(test)]
mod tests {
    use symbios_texture::for_each_texture_field;

    /// A `layout` list decides what a panel draws, so a field missing from one
    /// disappears from the UI without any compiler complaint — the row still
    /// exists, it is simply never invoked. This compares the two lists by name
    /// for every config that has a layout, so an omission, a duplicate or a
    /// typo fails here instead of silently losing a control.
    #[test]
    fn every_layout_lists_every_editable_field() {
        let mut checked = 0usize;

        macro_rules! check_layouts {
            (
                $(
                    $Config:ty, $header:literal, $editor:ident
                    $(, fixup $fixup:ident )?
                    { $(
                        $kind:ident ( $field:ident $($rest:tt)* )
                        $( explore ( $xlo:expr, $xhi:expr ) )?
                    ),+ $(,)? }
                    $( layout { $($step:tt)* } )?
                ),+ $(,)?
            ) => {
                $( check_layouts!(
                    @one $header, [ $( $kind ($field $($rest)*) ),+ ]
                    $( layout { $($step)* } )?
                ); )+
            };

            (@one $header:literal, [ $( $kind:ident ( $field:ident $($rest:tt)* ) ),+ ]
             layout { $($step:tt)* }) => {{
                // A row with no label is a field that is deliberately not
                // editable, and contributes nothing to a panel.
                let mut rows: Vec<&str> =
                    [ $( check_layouts!(@row $kind ($field $($rest)*)) ),+ ]
                        .into_iter()
                        .flatten()
                        .collect();
                let mut steps: Vec<&str> =
                    Vec::from(check_layouts!(@steps [] $($step)*));
                rows.sort_unstable();
                steps.sort_unstable();
                assert!(!rows.is_empty(), "the {} panel has no fields", $header);
                assert_eq!(
                    rows, steps,
                    "the {} panel's layout and its editable fields disagree",
                    $header
                );
                checked += 1;
            }};
            // No layout list: the panel draws its fields in table order, so
            // there is nothing that can fall out of step.
            (@one $header:literal, [ $($rows:tt)* ]) => {};

            (@row $kind:ident ($field:ident, none $($rest:tt)*)) => { None };
            (@row $kind:ident ($field:ident $($rest:tt)*)) => { Some(stringify!($field)) };

            // Walk the layout, collecting field names and dropping the two
            // presentation-only steps.
            (@steps [$($name:expr,)*]) => { [$($name,)*] };
            (@steps [$($name:expr,)*] , $($rest:tt)*) => {
                check_layouts!(@steps [$($name,)*] $($rest)*)
            };
            (@steps [$($name:expr,)*] separator() $($rest:tt)*) => {
                check_layouts!(@steps [$($name,)*] $($rest)*)
            };
            (@steps [$($name:expr,)*] text($text:literal) $($rest:tt)*) => {
                check_layouts!(@steps [$($name,)*] $($rest)*)
            };
            (@steps [$($name:expr,)*] $field:ident $($rest:tt)*) => {
                check_layouts!(@steps [$($name,)* stringify!($field),] $($rest)*)
            };
        }

        for_each_texture_field!(check_layouts);

        assert_eq!(
            checked, 7,
            "seven configs list their fields in an order that differs from the \
             table's: Bark, Leaf, Twig, Metal, Gravel, Flower, LeafSprite. If \
             this count drops, a layout list was removed and that panel \
             silently reordered."
        );
    }
}
