//! Egui UI helpers for editing texture generator configs.
//!
//! Provides reusable widgets for every texture config type so any application
//! with `bevy_egui` can embed texture parameter controls without duplicating
//! editor code.
//!
//! # Signature convention
//!
//! Every config editor has the form:
//! ```text
//! pub fn xxx_config_editor(ui: &mut egui::Ui, cfg: &mut XxxConfig, id: egui::Id) -> (bool, bool)
//! ```
//!
//! - `id` — used as the collapsing-header id salt; build with `egui::Id::new(x)`
//!   or derive a child ID via `parent.with("label")`.
//! - Returns `(writeback, regen)`:
//!   - `writeback` — any widget changed (including mid-drag). Write the config
//!     back to your resource to prevent slider snap-back.
//!   - `regen` — a value was *committed*: drag ended or a non-drag widget changed.
//!     Only regenerate the texture when this is `true`.
//!
//! # Where the panels come from
//!
//! Every editor function is generated by `impl_config_editor!` as a callback
//! over [`symbios_texture::for_each_texture_field!`] — the core crate's
//! per-field registry, which is also where the `Genotype` impls and the
//! record-boundary envelope clamp come from. This module owns the *widget
//! vocabulary* (which control a field kind gets, and its debouncing) and
//! nothing about any individual field: a slider's range is the field's
//! envelope, authored once beside the range mutation and an application's
//! sanitiser use.
//!
//! Two columns of a registry row belong to this module. `label` is the ident
//! `none` on the six fields that are evolvable but not editable, which is how
//! they stay out of a panel. And an optional `layout { … }` list gives the
//! *display* order where it differs from the table's order — the table is in
//! mutation-draw order, which is behaviour rather than presentation — and is
//! the only place `separator()` and `text("…")` may appear.
//!
//! Enabled via the `egui` Cargo feature.

use bevy_egui::egui;
use symbios_texture::for_each_texture_field;

// ---------------------------------------------------------------------------
// Declarative macro for config editors
// ---------------------------------------------------------------------------

/// Generates a public editor function for every config in the per-field
/// registry.
///
/// # Widget kinds
///
/// The mapping from a registry row's kind to a widget is total — there is no
/// debounced integer field and no instant slider — so a row carries no widget
/// column of its own.
///
/// | Row kind | Widget | Commit semantics |
/// |----------|--------|------------------|
/// | `f64`, `f32` | Slider over the field's envelope | debounced: writeback on change, regen on commit |
/// | `f64_round` | The same, stepping by 1 | debounced |
/// | `usize` | Integer slider | immediate: both on change |
/// | `seed` | Drag value | immediate |
/// | `color3` | Colour picker | immediate |
/// | `bool` | Checkbox | immediate |
/// | `enum_pick` | Row of selectable labels | immediate |
/// | `nested` | The sub-config's own editor, salted | merged |
///
/// A row whose label is `none` draws nothing; `separator()` and `text("…")`
/// come from the `layout` list, never from a row. The `explore` clause and a
/// `fixup` name are the core crate's business and are matched and discarded.
macro_rules! impl_config_editor {
    // Callback entry: one editor function per registry entry.
    (
        $(
            $Config:ty, $header:literal, $editor:ident
            $(, fixup $fixup:ident )?
            { $(
                $kind:ident ( $field:ident $($rest:tt)* )
                $( explore ( $xlo:expr, $xhi:expr ) )?
            ),+ $(,)? }
            $( layout { $($layout:tt)* } )?
        ),+ $(,)?
    ) => {
        $(
            #[doc = concat!(
                "Renders every editable [`", stringify!($Config),
                "`] parameter inside a collapsing header."
            )]
            pub fn $editor(
                ui: &mut egui::Ui,
                cfg: &mut $Config,
                id: egui::Id,
            ) -> (bool, bool) {
                let mut wb = false;
                let mut regen = false;
                egui::CollapsingHeader::new($header)
                    .id_salt(id)
                    .show(ui, |ui| {
                        // `ui` here is the closure's, shadowing the argument;
                        // both are written in this template, so passing it on
                        // keeps the widgets inside the header.
                        impl_config_editor!(@body ui, cfg, id, wb, regen,
                            rows { $( $kind ($field $($rest)*) ),+ }
                            $( layout { $($layout)* } )?
                        );
                    });
                (wb, regen)
            }
        )+
    };

    // --- panel body ---------------------------------------------------------

    // No layout list: the panel lists its fields in table order, and a row
    // with no label expands to nothing.
    (@body $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     rows { $( $kind:ident ( $field:ident $($rest:tt)* ) ),+ }) => {
        $( impl_config_editor!(
            @widget $ui, $cfg, $id, $wb, $regen, $kind ($field $($rest)*)
        ); )+
    };

    // With one: each row becomes an arm of a local `widget!`, and the list
    // says what to draw and in what order. The arms carry no `$` of their
    // own, which is what makes a macro definable from inside a macro.
    (@body $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     rows { $( $kind:ident ( $field:ident $($rest:tt)* ) ),+ }
     layout { $($step:tt)* }) => {
        macro_rules! widget {
            $( ( $field ) => {
                impl_config_editor!(
                    @widget $ui, $cfg, $id, $wb, $regen, $kind ($field $($rest)*)
                );
            }; )+
        }
        impl_config_editor!(@steps widget, $ui, $($step)*);
    };

    // --- layout walker ------------------------------------------------------

    (@steps $w:ident, $ui:ident,) => {};
    (@steps $w:ident, $ui:ident, , $($rest:tt)*) => {
        impl_config_editor!(@steps $w, $ui, $($rest)*);
    };
    (@steps $w:ident, $ui:ident, separator() $($rest:tt)*) => {
        $ui.separator();
        impl_config_editor!(@steps $w, $ui, $($rest)*);
    };
    (@steps $w:ident, $ui:ident, text($text:literal) $($rest:tt)*) => {
        $ui.label($text);
        impl_config_editor!(@steps $w, $ui, $($rest)*);
    };
    (@steps $w:ident, $ui:ident, $field:ident $($rest:tt)*) => {
        $w!($field);
        impl_config_editor!(@steps $w, $ui, $($rest)*);
    };

    // --- widget arms --------------------------------------------------------

    // A `none` label means evolvable but not editable: no widget at all.
    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     $kind:ident ($field:ident, none $($rest:tt)*)) => {};

    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     seed ($field:ident, $label:literal)) => {
        u32_instant($ui, &mut $cfg.$field, $label, &mut $wb, &mut $regen);
    };
    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     f64 ($field:ident, $label:literal, $min:expr, $max:expr, $half:expr)) => {
        slider_debounced(
            $ui,
            egui::Slider::new(&mut $cfg.$field, $min..=$max).text($label),
            &mut $wb,
            &mut $regen,
        );
    };
    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     f32 ($field:ident, $label:literal, $min:expr, $max:expr, $half:expr)) => {
        slider_debounced(
            $ui,
            egui::Slider::new(&mut $cfg.$field, $min..=$max).text($label),
            &mut $wb,
            &mut $regen,
        );
    };
    // A field the search rounds is a count, so its slider steps like one.
    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     f64_round ($field:ident, $label:literal, $min:expr, $max:expr, $half:expr)) => {
        slider_debounced(
            $ui,
            egui::Slider::new(&mut $cfg.$field, $min..=$max)
                .step_by(1.0)
                .text($label),
            &mut $wb,
            &mut $regen,
        );
    };
    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     usize ($field:ident, $label:literal, $min:expr, $max:expr)) => {
        usize_instant($ui, &mut $cfg.$field, $min..=$max, $label, &mut $wb, &mut $regen);
    };
    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     color3 ($field:ident, $label:literal, $half:expr)) => {
        color_instant($ui, $label, &mut $cfg.$field, &mut $wb, &mut $regen);
    };
    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     bool ($field:ident, $label:literal)) => {
        bool_instant($ui, &mut $cfg.$field, $label, &mut $wb, &mut $regen);
    };
    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     enum_pick ($field:ident, $label:literal, [ $(($variant:expr, $btn:literal)),+ ])) => {
        $ui.horizontal(|ui| {
            ui.label($label);
            $(
                let selected = $cfg.$field == $variant;
                if ui.selectable_label(selected, $btn).clicked() && !selected {
                    $cfg.$field = $variant;
                    $wb = true;
                    $regen = true;
                }
            )+
        });
    };
    (@widget $ui:ident, $cfg:ident, $id:ident, $wb:ident, $regen:ident,
     nested ($field:ident, $sub:ty, $sub_editor:ident, $salt:literal)) => {
        let (sub_wb, sub_regen) = $sub_editor($ui, &mut $cfg.$field, $id.with($salt));
        $wb |= sub_wb;
        $regen |= sub_regen;
    };
}

